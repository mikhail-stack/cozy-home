import { describe, expect, it } from "vitest";
import { normalizeUaPhone } from "./phone.js";

describe("normalizeUaPhone", () => {
  it.each([
    ["+380501234567"],
    ["380501234567"],
    ["0501234567"],
    ["80501234567"],
    ["+38 050 123 45 67"],
    ["+380 (50) 123-45-67"],
    ["(050) 123-45-67"],
    ["050.123.45.67"],
    ["  0501234567  "],
  ])("%s → +380501234567", (input) => {
    expect(normalizeUaPhone(input)).toBe("+380501234567");
  });

  it("городские номера (044, 032) тоже принимаются", () => {
    expect(normalizeUaPhone("044 123 45 67")).toBe("+380441234567");
    expect(normalizeUaPhone("+380321234567")).toBe("+380321234567");
  });

  it.each([
    ["пусто", ""],
    ["буквы", "abc"],
    ["буквы среди цифр", "050123abcd"],
    ["слишком короткий", "050123456"],
    ["слишком длинный", "05012345678"],
    ["длинный с кодом страны", "3805012345678"],
    ["чужой код страны", "+48501234567"],
    ["чужой код без плюса", "48501234567"],
    ["плюс перед национальным видом", "+0501234567"],
    ["плюс не в начале", "380+501234567"],
    ["несуществующий код региона (02x)", "0201234567"],
    ["без ведущего нуля", "501234567"],
  ])("%s → null", (_name, input) => {
    expect(normalizeUaPhone(input)).toBeNull();
  });
});
